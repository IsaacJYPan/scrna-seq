#!/usr/bin/env Rscript
runtime <- new.env(parent = globalenv())
sys.source(file.path("r-backend", "plumber.R"), envir = runtime)
set.seed(42)
counts <- matrix(sample(1:9, 40, replace = TRUE), nrow = 4,
                 dimnames = list(paste0("Gene", 1:4), paste0("Cell", 1:10)))
runtime$global_obj <- Seurat::CreateSeuratObject(counts, min.cells = 0, min.features = 0)
runtime$live_revision <- 1
first <- runtime$make_provenance(list(n = 10), "ncol(object)", "pca", c("Seurat", "notInstalledPackage"), list(dims = 2))
stopifnot(grepl("^[a-f0-9]{64}$", first$provenance$execution$generation))
stopifnot(identical(first$provenance$execution$order, 1))
stopifnot(identical(first$provenance$execution$packages[[1]]$version, as.character(utils::packageVersion("Seurat"))))
stopifnot(is.null(first$provenance$execution$packages[[2]]$version))
stopifnot(grepl("Z$", first$provenance$timestamp))
runtime$mark_live_session_changed()
second <- runtime$make_provenance(list(n = 10), "object <- subset(object)", "subset")
stopifnot(identical(second$provenance$execution$generation, first$provenance$execution$generation))
stopifnot(identical(second$provenance$execution$order, 2))
stopifnot(identical(second$live_state$live_revision, 2))
runtime$restore_active_session(list(global = runtime$global_obj, raw = runtime$global_obj, live_revision = 0, saved_revision = 0))
third <- runtime$make_provenance(list(n = 10), "ncol(object)", "pca")
stopifnot(identical(third$provenance$execution$order, 3))
stopifnot(identical(third$live_state$live_revision, 0))
fresh <- new.env(parent = globalenv())
sys.source(file.path("r-backend", "plumber.R"), envir = fresh)
stopifnot(!identical(fresh$r_execution_generation, runtime$r_execution_generation), identical(fresh$r_execution_order, 0))
cat("PASS: actual R provenance retains observed packages, UTC time and process generation/order across live revision resets\n")
