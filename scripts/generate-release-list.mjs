#!/usr/bin/env node
// Writes docs/workflow-releases.md from the release catalog, so the documents
// that describe what an agent may run cannot drift from what the server allows.
//   node scripts/generate-release-list.mjs          write the file
//   node scripts/generate-release-list.mjs --check  exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'docs', 'workflow-releases.md');

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const code = (values) => (values.length ? values.map((v) => `\`${v}\``).join(', ') : '—');

function inputText(input) {
  if (input.kind === 'analysis_object') {
    const stage = input.requiresStage ? ` (${input.requiresStage} stage or later)` : '';
    return `Accepted result of ${code(input.fromReleases)}${stage}`;
  }
  return `${input.multiple ? 'Datasets' : 'Dataset'}: ${code(input.fileTypes || [])}`;
}

function metricsText(metrics) {
  const selectable = metrics.filter((m) => m.kind !== 'inferential').map((m) => m.key);
  const reported = metrics.filter((m) => m.kind === 'inferential').map((m) => m.key);
  return [
    selectable.length ? `selectable: ${code(selectable)}` : 'none selectable',
    reported.length ? `inferential (not selectable): ${code(reported)}` : '',
  ].filter(Boolean).join('; ');
}

export function renderReleaseList() {
  const { currentReleases } = require(path.join(root, 'backend', 'workflowTrust', 'catalog.js'));
  const releases = currentReleases();
  const builtIn = releases.filter((r) => r.jobType !== 'trusted.method.v1');
  const library = releases.filter((r) => r.jobType === 'trusted.method.v1');
  const row = (release) => {
    const schema = release.definition.parameterSchema || {};
    const design = Object.keys(schema).filter((name) => schema[name].role === 'design');
    return `| \`${release.key}\` | ${cell(release.title)} | \`${release.jobType}\` | ${cell(
      release.definition.inputs.map(inputText).join('; ')
    )} | ${code(design)} | ${cell(metricsText(release.definition.selectableMetrics || []))} |`;
  };
  const header = [
    '| Release | Title | Job type | Input | Design parameters (a person fixes) | Metrics |',
    '| --- | --- | --- | --- | --- | --- |',
  ];
  return [
    '# Workflow releases',
    '',
    '<!-- Generated by scripts/generate-release-list.mjs from backend/workflowTrust/catalog.js. Do not edit. -->',
    '',
    'These are the only workflows an agent can run. Each is approved per project by',
    'its exact digest (see [agent automation](agent-automation.md#approved-workflow-execution-phase-2)).',
    'Design parameters define the scientific question: a study fixes them and an',
    'agent can never vary them. Studies can rank trials only by selectable',
    '(descriptive or quality) metrics; inferential metrics are reported but never',
    'used to choose a trial.',
    '',
    `## Built-in releases (${builtIn.length})`,
    '',
    ...header,
    ...builtIn.map(row),
    '',
    `## Trusted method library (${library.length})`,
    '',
    'Each method is one R file and one entry in',
    '[`trusted-methods/catalog.json`](../trusted-methods/README.md), run in the isolated',
    'sandbox under job type `trusted.method.v1`.',
    '',
    ...header,
    ...library.map(row),
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = renderReleaseList();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== text) {
      console.error('docs/workflow-releases.md is out of date. Run: node scripts/generate-release-list.mjs');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(target, text);
    console.log(`Wrote ${path.relative(root, target)}`);
  }
}
